function getQuestion(id) {
  const question = byId.get(id);
  if (!question) throw new Error(`Cleanup target is missing: ${id}`);
  return question;
}

function update(id, changes) {
  const question = getQuestion(id);
  if (changes.q !== undefined) question.q = changes.q;
  if (changes.answer !== undefined) question.answer = changes.answer;
  if (changes.options) Object.assign(question.options, changes.options);
}

function replaceText(id, replacements) {
  const question = getQuestion(id);
  const apply = value => replacements.reduce(
    (text, [before, after]) => text.split(before).join(after),
    value,
  );
  question.q = apply(question.q);
  for (const letter of ['A', 'B', 'C', 'D']) {
    question.options[letter] = apply(question.options[letter]);
  }
}

